#!/usr/bin/env node
/*
 * Builds the BACnet files for the MultiTech Conduit gateway (mPower, Payload Management).
 *
 * The source is the French definition fr/<famille>/<product>/<product>-bacnet-definition.json:
 * the BACnet properties of the product (name, type, units, downlink).
 * For each product and each language this script writes, next to the codec:
 *   - <product>-bacnet-definition.json (en/ only): the French definition with English names;
 *   - <product>-bacnet-codec.js: the codec of that language, followed by a BACnet layer that keeps
 *     the declared properties only and turns every value into a single value of the declared type
 *     (most recent sample of a historised frame, 1/0 for an input state label).
 *
 * Optional: fr/<famille>/<product>/<product>-bacnet-constants.json gives texts sent with every
 * uplink, in both languages ({ "name": { "fr": "...", "en": "..." } }), for example the format of
 * the writable objects. Each name must be declared as a string property in the definition.
 *
 * Usage:
 *   node scripts/build-bacnet.js           write the files
 *   node scripts/build-bacnet.js --check   exit with an error if a file is not up to date
 */
"use strict";

const fs = require("fs");
const path = require("path");
const T = require("./lib/i18n");

const ROOT = path.resolve(__dirname, "..");
const CHECK = process.argv.includes("--check");
const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));

// Input state labels of the change-of-state frames -> BACnet value.
const STATES_FR = { "état haut": 1, "état bas": 0, "mise à l'état haut": 1, "mise à l'état bas": 0 };
const STATES = {
    fr: STATES_FR,
    en: Object.fromEntries(Object.entries(STATES_FR).map(([label, v]) => [T.STRINGS[label], v])),
};

const stale = [];
function output(file, content) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === content) return;
    if (CHECK) {
        stale.push(path.relative(ROOT, file));
        return;
    }
    fs.writeFileSync(file, content);
    console.log("wrote " + path.relative(ROOT, file));
}

function englishDefinition(frDef, enProduct) {
    const properties = {};
    for (const [name, prop] of Object.entries(frDef.properties)) {
        const en = T.renameId(name);
        if (has(properties, en)) throw new Error(`${enProduct.id}: two BACnet properties named ${en}`);
        properties[en] = prop.name ? Object.assign({}, prop, { name: en }) : prop;
    }
    return Object.assign({}, frDef, { description: `${enProduct.name}: ${enProduct.summary}`, properties });
}

const TEXT = {
    fr: {
        title: "codec BACnet pour la passerelle MultiTech Conduit (mPower)",
        body: [
            "Fichier à importer avec <produit>-bacnet-definition.json (Payload Management > Sensor Definitions).",
            "Il contient le codec français, suivi d'une couche BACnet qui ne garde que les propriétés",
            "déclarées et rend une seule valeur par propriété (échantillon le plus récent d'une trame historisée).",
            "Généré par scripts/build-bacnet.js : modifiez le codec ou la définition, puis régénérez.",
        ],
        layer: "Couche BACnet : une valeur par propriété déclarée",
    },
    en: {
        title: "BACnet codec for the MultiTech Conduit gateway (mPower)",
        body: [
            "Import this file with <product>-bacnet-definition.json (Payload Management > Sensor Definitions).",
            "It contains the English codec, followed by a BACnet layer that keeps the declared properties",
            "only and returns one value per property (most recent sample of a historised frame).",
            "Generated by scripts/build-bacnet.js: edit the French codec or definition, then rebuild.",
        ],
        layer: "BACnet layer: one value per declared property",
    },
};

function bacnetCodec(code, product, def, lang, constants) {
    const t = TEXT[lang];
    let core = code.replace(/\r\n/g, "\n").replace(/^\/\*\*[\s\S]*?\*\/\n+/, "");
    const marker = core.search(/\n\/\* -{75}\n \* (Platform adapters|Adaptateurs de plateformes)/);
    if (marker < 0) throw new Error(product.id + ": platform adapters not found");
    core = core.slice(0, marker);
    if (!/^function decodeUplink\(input\) \{/m.test(core)) throw new Error(product.id + ": decodeUplink not found");
    core = core.replace(/^function decodeUplink\(input\) \{/m, "function decodeUplinkCodec(input) {");

    const uplink = Object.entries(def.properties).filter(([, p]) => !p.downlink && !p.name);
    const props = uplink.map(([name, p]) => `    ${JSON.stringify(name)}: ${JSON.stringify(p.type)}`).join(",\n");
    const states = Object.entries(STATES[lang]).map(([k, v]) => `    ${JSON.stringify(k)}: ${v}`).join(",\n");
    const constantLines = Object.entries(constants).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n");
    const constantBlock = constantLines ? `
var BACNET_CONSTANTS = {
${constantLines}
};
` : "";
    const constantLoop = constantLines ? `    for (var name in BACNET_CONSTANTS) {
        if (Object.prototype.hasOwnProperty.call(BACNET_CONSTANTS, name)) data[name] = BACNET_CONSTANTS[name];
    }
` : "";
    const entries = ["decodeUplink"].concat(/function encodeDownlink\s*\(/.test(core) ? ["encodeDownlink"] : []);

    return `/**
 * ATIM ${product.name} – ${t.title}
 * ${product.version} – ${lang === "fr" ? "sortie en français" : "English output"}
 *
${t.body.map((l) => " * " + l).join("\n")}
 *
 * Copyright (c) 2026 ATIM – SPDX-License-Identifier: MIT
 */

${core.replace(/\s+$/, "\n")}
/* ---------------------------------------------------------------------------
 * ${t.layer}
 * ------------------------------------------------------------------------- */

var BACNET_PROPERTIES = {
${props}
};

var BACNET_STATES = {
${states}
};
${constantBlock}
function bacnetValue(value, type) {
    if (Object.prototype.toString.call(value) === "[object Array]") {
        value = value.length > 0 ? value[0] : undefined;
    }
    if (value === undefined || value === null) return undefined;
    if (type === "string") return typeof value === "object" ? JSON.stringify(value) : String(value);
    if (typeof value === "string" && Object.prototype.hasOwnProperty.call(BACNET_STATES, value)) {
        value = BACNET_STATES[value];
    }
    if (typeof value === "boolean") value = value ? 1 : 0;
    return typeof value === "number" && isFinite(value) ? value : undefined;
}

function decodeUplink(input) {
    var result = decodeUplinkCodec(input);
    var data = {};
    for (var key in result.data) {
        if (!Object.prototype.hasOwnProperty.call(result.data, key)) continue;
        if (!Object.prototype.hasOwnProperty.call(BACNET_PROPERTIES, key)) continue;
        var value = bacnetValue(result.data[key], BACNET_PROPERTIES[key]);
        if (value !== undefined) data[key] = value;
    }
${constantLoop}    result.data = data;
    return result;
}

/* Node.js / CommonJS */
if (typeof module !== "undefined" && module.exports) {
${entries.map((f) => `    module.exports.${f} = ${f};`).join("\n")}
}
`;
}

const frIndex = readJson(path.join(ROOT, "fr", "products.json"));
const enIndex = readJson(path.join(ROOT, "en", "products.json"));

for (const fr of frIndex) {
    const en = enIndex.find((p) => p.id === fr.id);
    if (!en) throw new Error(fr.id + ": missing from en/products.json (run npm run build:en first)");
    const defName = `${fr.id}-bacnet-definition.json`;
    const codecName = `${fr.id}-bacnet-codec.js`;
    const frDefFile = path.join(ROOT, "fr", fr.path, defName);
    if (!fs.existsSync(frDefFile)) {
        console.log(`note: ${fr.id} has no BACnet definition (${path.relative(ROOT, frDefFile)})`);
        continue;
    }
    const frDef = readJson(frDefFile);
    if (frDef.decoder !== codecName) throw new Error(`${fr.id}: "decoder" must be ${codecName}`);
    const enDef = englishDefinition(frDef, en);
    const constantsFile = path.join(ROOT, "fr", fr.path, `${fr.id}-bacnet-constants.json`);
    const constants = { fr: {}, en: {} };
    if (fs.existsSync(constantsFile)) {
        for (const [name, texts] of Object.entries(readJson(constantsFile))) {
            if (!frDef.properties[name] || frDef.properties[name].type !== "string") {
                throw new Error(`${fr.id}: constant ${name} must be a string property of the definition`);
            }
            if (!texts.fr || !texts.en) throw new Error(`${fr.id}: constant ${name} needs "fr" and "en"`);
            constants.fr[name] = texts.fr;
            constants.en[T.renameId(name)] = texts.en;
        }
    }
    output(path.join(ROOT, "en", en.path, defName), JSON.stringify(enDef, null, 4) + "\n");

    for (const [lang, product, def] of [["fr", fr, frDef], ["en", en, enDef]]) {
        const dir = path.join(ROOT, lang, product.path);
        const code = fs.readFileSync(path.join(dir, product.codec), "utf8");
        output(path.join(dir, codecName), bacnetCodec(code, product, def, lang, constants[lang]));
    }
}

if (CHECK) {
    if (stale.length) {
        console.log("BACnet files are not up to date. Run: npm run build");
        for (const f of stale) console.log("  " + f);
        process.exit(1);
    }
    console.log("BACnet files are up to date");
}
