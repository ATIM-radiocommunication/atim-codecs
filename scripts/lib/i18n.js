function matchCase(source, word) {
  if (source === source.toUpperCase() && source.length > 1) return word.toUpperCase();
  if (source[0] === source[0].toUpperCase()) return word[0].toUpperCase() + word.slice(1);
  return word;
}

function renameId(name) {
  if (Object.prototype.hasOwnProperty.call(OVERRIDES, name)) return OVERRIDES[name];
  // segments: words (camelCase aware), digits and separators
  return name.replace(/[A-Z]?[a-z]+|[A-Z]+(?![a-z])/g, (seg) => {
    const key = seg.toLowerCase();
    return Object.prototype.hasOwnProperty.call(WORDS, key) ? matchCase(seg, WORDS[key]) : seg;
  });
}

