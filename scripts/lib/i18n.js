// Translate a FR decoder output value (whole label, or composed alert) to English.
const FRAGMENTS = Object.keys(STRINGS).filter((k) => k.startsWith(' ')).sort((a, b) => b.length - a.length);
function valueEn(v) {
  if (typeof v === 'string') {
    if (Object.prototype.hasOwnProperty.call(STRINGS, v)) return STRINGS[v];
    let s = v;
    // composed alert: "<kind><fragments...>"
    const heads = ['Retour entre les seuils', 'Dépassement du seuil haut', 'Dépassement du seuil bas'];
    s = s.split(' | ').map((part) => {
      for (const h of heads) if (part.startsWith(h)) return STRINGS[h] + part.slice(h.length);
      return part;
    }).join(' | ');
    for (const f of FRAGMENTS) s = s.split(f).join(STRINGS[f]);
    // labels assembled from pieces: "Lun, Mar · 08:00-18:00 UTC · Confort"
    s = s.split(' · ').map((part) => part.split(', ').map((piece) =>
      Object.prototype.hasOwnProperty.call(STRINGS, piece) ? STRINGS[piece] : piece).join(', ')).join(' · ');
    return s;
  }
  if (Array.isArray(v)) return v.map(valueEn);
  if (v && typeof v === 'object') {
    const o = {};
    for (const k of Object.keys(v)) o[k] = valueEn(v[k]);
    return o;
  }
  return v;
}
function dataEn(data) {
  const out = {};
  for (const k of Object.keys(data)) {
    out[renameId(k)] = valueEn(data[k]);
  }
  return out;
}

